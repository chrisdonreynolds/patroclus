def is_excluded_parlay_or_combo(market: Dict[str, Any]) -> bool:
    ticker = (market.get("ticker") or "").upper()
    event_ticker = (market.get("event_ticker") or "").upper()
    title = (market.get("title") or "").lower()

    if any(
        ticker.startswith(pref) or event_ticker.startswith(pref)
        for pref in EXCLUDED_TICKER_PREFIXES
    ):
        return True
    if "crosscategory" in ticker.lower() or "crosscategory" in event_ticker.lower():
        return True
    # Multi-leg parlays list comma-separated "yes X, yes Y, no Z" legs in title
    if title.count(",yes ") + title.count(",no ") + title.count(", yes ") + title.count(", no ") >= 2:
        return True
    return False


def classify_orthogonality_bucket(market: Dict[str, Any]) -> str:
    ticker = (market.get("ticker") or "").upper()
    event_ticker = (market.get("event_ticker") or "").upper()
    title = (market.get("title") or "").lower()
    category = (market.get("category") or "").lower()

    for bucket, prefixes in TARGET_SERIES_BY_BUCKET.items():
        if any(
            ticker.startswith(p) or event_ticker.startswith(p) for p in prefixes
        ):
            return bucket

    if any(
        k in ticker or k in event_ticker or k in title or k in category
        for k in ("HIGH", "LOWT", "TEMP", "WEATHER", "RAIN", "SNOW", "HURRICANE")
    ):
        return "BUCKET_A_WEATHER_ATMOSPHERIC"

    if any(
        k in ticker or k in event_ticker or k in title or k in category
        for k in (
            "GAS",
            "AAA",
            "WTI",
            "OIL",
            "CPI",
            "PCE",
            "INFLATION",
            "FED",
            "FOMC",
            "GDP",
            "PAYROLL",
            "TREASURY",
        )
    ):
        return "BUCKET_B_MACRO_ENERGY_COMMODITY"

    return "BUCKET_C_CORPORATE_PROCEDURAL_ENTERTAINMENT_SPACE"


def parse_expiration_hours(market: Dict[str, Any], now_utc: dt.datetime) -> Optional[float]:
    exp_str = (
        market.get("expiration_time")
        or market.get("expected_expiration_time")
        or market.get("close_time")
    )
    if not exp_str:
        return None
    try:
        exp_dt = dt.datetime.fromisoformat(exp_str.replace("Z", "+00:00"))
        delta_hours = (exp_dt - now_utc).total_seconds() / 3600.0
        return round(delta_hours, 2)
    except Exception:
        return None


def harvest_kalshi_markets(max_general_pages: int = 15) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    seen_tickers = set()
    harvested: List[Dict[str, Any]] = []
    pages_fetched = 0

    # Pass 1: Directly query every target series across Buckets A, B, and C
    for bucket, series_list in TARGET_SERIES_BY_BUCKET.items():
        for series_ticker in series_list:
            resp = safe_get(
                KALSHI_MARKETS_URL,
                params={"status": "open", "series_ticker": series_ticker, "limit": 200},
                timeout=12,
            )
            if resp is not None and resp.status_code == 200:
                pages_fetched += 1
                for m in resp.json().get("markets", []):
                    tkr = m.get("ticker")
                    if tkr and tkr not in seen_tickers and not is_excluded_parlay_or_combo(m):
                        seen_tickers.add(tkr)
                        harvested.append(m)

    # Pass 2: General open market pagination (excluding all KXMVE* parlays)
    cursor = None
    for _ in range(max_general_pages):
        params: Dict[str, Any] = {"status": "open", "limit": 200}
        if cursor:
            params["cursor"] = cursor
        resp = safe_get(KALSHI_MARKETS_URL, params=params, timeout=15)
        if resp is None or resp.status_code != 200:
            break
        pages_fetched += 1
        data = resp.json()
        markets = data.get("markets", [])
        if not markets:
            break
        for m in markets:
            tkr = m.get("ticker")
            if tkr and tkr not in seen_tickers and not is_excluded_parlay_or_combo(m):
                seen_tickers.add(tkr)
                harvested.append(m)
        cursor = data.get("cursor")
        if not cursor:
            break

    stats = {
        "pages_fetched": pages_fetched,
        "total_open_markets_scanned": len(harvested),
    }
    return harvested, stats


def parse_orderbook_levels(raw_levels: Any) -> List[Tuple[int, int]]:
    parsed: List[Tuple[int, int]] = []
    if not isinstance(raw_levels, list):
        return parsed
    for item in raw_levels:
        if isinstance(item, (list, tuple)) and len(item) >= 2:
            try:
                p_raw, q_raw = item[0], item[1]
                price_cents = (
                    int(round(float(p_raw) * 100))
                    if isinstance(p_raw, str) and "." in p_raw
                    else int(float(p_raw))
                )
                qty = int(float(q_raw))
                if 1 <= price_cents <= 99 and qty > 0:
                    parsed.append((price_cents, qty))
            except Exception:
                continue
    parsed.sort(key=lambda x: x[0], reverse=True)
    return parsed


def batch_fetch_orderbooks(tickers: List[str]) -> Dict[str, Dict[str, List[Tuple[int, int]]]]:
    orderbooks: Dict[str, Dict[str, List[Tuple[int, int]]]] = {}
    unique_tickers = list(dict.fromkeys([t for t in tickers if t]))

    for i in range(0, len(unique_tickers), 100):
        chunk = unique_tickers[i : i + 100]
        resp = safe_get(
            KALSHI_ORDERBOOKS_BATCH_URL,
            params={"tickers": ",".join(chunk)},
            timeout=20,
        )
        if resp is not None and resp.status_code == 200:
            data = resp.json()
            raw_obs = data.get("orderbooks", data)
            if isinstance(raw_obs, list):
                for entry in raw_obs:
                    tkr = entry.get("market_ticker") or entry.get("ticker")
                    ob_body = entry.get("orderbook", entry)
                    if tkr and isinstance(ob_body, dict):
                        yes_lvls = parse_orderbook_levels(
                            ob_body.get("yes") or ob_body.get("yes_dollars") or []
                        )
                        no_lvls = parse_orderbook_levels(
                            ob_body.get("no") or ob_body.get("no_dollars") or []
                        )
                        orderbooks[tkr] = {"yes": yes_lvls, "no": no_lvls}
    return orderbooks


def extract_cents(market: Dict[str, Any], cents_key: str, dollars_key: str) -> int:
    val = market.get(cents_key)
    if val is not None:
        try:
            return int(round(float(val)))
        except Exception:
            pass
    d_val = market.get(dollars_key)
    if d_val is not None:
        try:
            return int(round(float(d_val) * 100))
        except Exception:
            pass
    return 0


def evaluate_candidates(
    markets: List[Dict[str, Any]],
    bankroll_info: Dict[str, Any],
    weather_oracles: Dict[str, Any],
    now_utc: dt.datetime,
) -> List[Dict[str, Any]]:
    # Pre-filter markets in target window (4h to 96h) that are not 99c/1c dead books
    preliminary: List[Dict[str, Any]] = []
    event_yes_sum: Dict[str, int] = {}
    event_counts: Dict[str, int] = {}

    for m in markets:
        hrs = parse_expiration_hours(m, now_utc)
        if hrs is None or not (4.0 <= hrs <= 96.0):
            continue
        yes_bid = extract_cents(m, "yes_bid", "yes_bid_dollars")
        no_bid = extract_cents(m, "no_bid", "no_bid_dollars")
        evt = m.get("event_ticker") or m.get("ticker") or ""
        if no_bid > 0:
            implied_yes = 100 - no_bid
            event_yes_sum[evt] = event_yes_sum.get(evt, 0) + implied_yes
            event_counts[evt] = event_counts.get(evt, 0) + 1

        # Quick pre-filter: require two-sided quote in or near the longshot zone
        if MIN_YES_BID_CENTS <= yes_bid <= MAX_YES_BID_CENTS and MIN_NO_BID_CENTS <= no_bid <= MAX_NO_BID_CENTS:
            m["_hours_to_expiration"] = hrs
            preliminary.append(m)

    orderbooks = batch_fetch_orderbooks([m["ticker"] for m in preliminary])
    candidates: List[Dict[str, Any]] = []
    max_risk = bankroll_info["max_dollar_risk_5pct"]
    total_bankroll = bankroll_info["total_liquid_bankroll_dollars"]

    for m in preliminary:
        tkr = m["ticker"]
        evt = m.get("event_ticker") or tkr
        ob = orderbooks.get(tkr, {"yes": [], "no": []})
        yes_levels = ob.get("yes", [])
        no_levels = ob.get("no", [])

        best_yes_bid = (
            yes_levels[0][0]
            if yes_levels
            else extract_cents(m, "yes_bid", "yes_bid_dollars")
        )
        best_no_bid = (
            no_levels[0][0]
            if no_levels
            else extract_cents(m, "no_bid", "no_bid_dollars")
        )
        last_price_yes = extract_cents(m, "last_price", "last_price_dollars")

        # HARD GATE 1: Never allow 0-bid or 99c/1c books
        if not (MIN_YES_BID_CENTS <= best_yes_bid <= MAX_YES_BID_CENTS):
            continue
        if not (MIN_NO_BID_CENTS <= best_no_bid <= MAX_NO_BID_CENTS):
            continue

        spread_cents = 100 - best_yes_bid - best_no_bid
        if not (MIN_SPREAD_CENTS <= spread_cents <= MAX_SPREAD_CENTS):
            continue

        top_no_queue = sum(q for _, q in no_levels[:2])
        total_no_qty = sum(q for _, q in no_levels)
        total_yes_qty = sum(q for _, q in yes_levels)

        # Require actual resting Yes demand so the market isn't one-sided
        if total_yes_qty == 0 and last_price_yes == 0:
            continue
        if top_no_queue > MAX_TOP_NO_QUEUE_DEPTH:
            continue

        denom = total_no_qty + total_yes_qty
        obi = round((total_no_qty - total_yes_qty) / denom, 4) if denom > 0 else 0.0
        high_adverse = abs(obi) > MAX_OBI_THRESHOLD
        if high_adverse:
            continue

        bucket = classify_orthogonality_bucket(m)

        # Weather Midnight Clocks Trap check
        matched_station = None
        if bucket == "BUCKET_A_WEATHER_ATMOSPHERIC":
            for st_code, st_meta in NWS_STATIONS.items():
                if any(tkr.upper().startswith(pref) for pref in st_meta["series_prefixes"]):
                    matched_station = weather_oracles.get("stations", {}).get(st_code)
                    break
            if matched_station and matched_station.get("midnight_clocks_trap_triggered"):
                continue

        rec_maker_no_bid = min(best_no_bid + 1, 96)
        implied_yes_ask = 100 - best_no_bid
        price_Per_contract = rec_maker_no_bid / 100.0
        contracts_to_bid = int(math.floor(max_risk / price_Per_contract))
        if contracts_to_bid < 1:
            continue

        total_exposure = round(contracts_to_bid * price_Per_contract, 2)
        max_profit = round(contracts_to_bid * (1.0 - price_Per_contract), 2)
        net_return_pct = round(((1.0 - price_Per_contract) / price_Per_contract) * 100.0, 2)

        p_prob = price_Per_contract
        taker_fee_per_contract = round(0.07 * p_prob * (1.0 - p_prob), 4)
        overround = round(event_yes_sum.get(evt, 100) / 100.0, 2)

        # Composite score: favors tight tradable spread, real Yes bid, low No queue, and event overround
        quality_score = (
            (best_yes_bid * 2.0)
            + (overround * 15.0)
            - (spread_cents * 1.2)
            - (top_no_queue * 0.005)
        )

        candidates.append(
            {
                "ticker": tkr,
                "event_ticker": evt,
                "title": m.get("title", ""),
                "subtitle": m.get("subtitle", ""),
                "kalshi_market_url": f"https://kalshi.com/markets/{evt.lower()}",
                "orthogonality_bucket": bucket,
                "hours_to_expiration": m["_hours_to_expiration"],
                "expiration_iso": m.get("expiration_time") or m.get("close_time"),
                "quality_score": round(quality_score, 3),
                "orderbook_pricing": {
                    "best_yes_bid_cents": best_yes_bid,
                    "best_no_bid_cents": best_no_bid,
                    "implied_yes_ask_cents": implied_yes_ask,
                    "last_price_yes_cents": last_price_yes,
                    "recommended_maker_no_bid_cents": rec_maker_no_bid,
                    "price_improvement_cents": 1,
                },
                "microstructure_metrics": {
                    "spread_cents": spread_cents,
                    "top_no_queue_depth": top_no_queue,
                    "total_no_bid_qty": total_no_qty,
                    "total_yes_bid_qty": total_yes_qty,
                    "obi": obi,
                    "event_overround": overround,
                    "taker_fee_saved_dollars_per_contract": taker_fee_per_contract,
                    "taker_fee_saved_cents_per_contract": round(taker_fee_per_contract * 100, 2),
                    "total_taker_fee_saved_on_position_dollars": round(
                        taker_fee_per_contract * contracts_to_bid, 2
                    ),
                    "high_adverse_selection_risk": high_adverse,
                },
                "position_sizing_5pct_cap": {
                    "total_bankroll_dollars": total_bankroll,
                    "max_dollar_risk_5pct": max_risk,
                    "contracts_to_bid": contracts_to_bid,
                    "total_order_exposure_dollars": total_exposure,
                    "max_profit_if_no_wins_dollars": max_profit,
                    "net_win_return_pct": net_return_pct,
                    "payoff_asymmetry_losses_to_wipe_wins": f"{round(price_Per_contract / (1.0 - price_Per_contract), 2)}-to-1",
                },
                "primary_truth_oracle": {
                    "weather_station": matched_station,
                    "event_field_inflation": {
                        "event_ticker": evt,
                        "candidate_count": event_counts.get(evt, 1),
                        "event_overround": overround,
                        "field_inflation_flagged": overround > 1.05,
                    },
                },
            }
        )

    candidates.sort(key=lambda x: x["quality_score"], reverse=True)
    return candidates


def select_orthogonal_top_candidates(
    all_candidates: List[Dict[str, Any]],
) -> Tuple[Dict[str, Optional[Dict[str, Any]]], List[Dict[str, Any]]]:
    buckets = [
        "BUCKET_A_WEATHER_ATMOSPHERIC",
        "BUCKET_B_MACRO_ENERGY_COMMODITY",
        "BUCKET_C_CORPORATE_PROCEDURAL_ENTERTAINMENT_SPACE",
    ]
    by_bucket: Dict[str, List[Dict[str, Any]]] = {
        b: [c for c in all_candidates if c["orthogonality_bucket"] == b]
        for b in buckets
    }

    selected_3: Dict[str, Optional[Dict[str, Any]]] = {
        b: (by_bucket[b][0] if by_bucket[b] else None) for b in buckets
    }

    # Build a balanced top 25 list (up to 8 per bucket first, then fill by score)
    balanced: List[Dict[str, Any]] = []
    seen = set()
    for b in buckets:
        for c in by_bucket[b][:8]:
            balanced.append(c)
            seen.add(c["ticker"])
    for c in all_candidates:
        if len(balanced) >= 25:
            break
        if c["ticker"] not in seen:
            balanced.append(c)
            seen.add(c["ticker"])

    return selected_3, balanced[:25]


